def build_icon():
    """The game's Windows icon: the mushroom cap of the Pip portrait, cropped inside its frame, as a multi-size .ico.

    The Export Game dialog takes an optional .ico (GameExportRequest.IconPath): pick `Mushroom Meadow.ico` from the
    template folder (or this folder). The window title of an export is the project's name, "Mushroom Meadow".
    """
    from PIL import Image
    with open(os.path.join(ASSETS, "Sprites", "Portrait Pip.image.json"), encoding="utf-8") as handle:
        frame = json.load(handle)["frames"][0]["source"]
    src = Image.open(os.path.join(ASSETS, "Sprites", frame.replace("/", os.sep))).convert("RGBA")
    inner = src.crop((6, 6, 58, 58))  # inside the portrait's gold frame
    big = inner.resize((256, 256), Image.NEAREST)
    sizes = [(16, 16), (24, 24), (32, 32), (48, 48), (64, 64), (128, 128), (256, 256)]
    for target in (os.path.join(HERE, "Mushroom Meadow.ico"), os.path.join(TEMPLATE, "Mushroom Meadow.ico")):
        big.save(target, format="ICO", sizes=sizes)
    return True


