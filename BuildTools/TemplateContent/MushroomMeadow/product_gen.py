def wrapped_block(blocks, width):
    """Flattens (heading, text) tips into parallel PGSL lists: line styles (0 heading, 1 text, 2 gap) and strings."""
    styles, lines = [], []
    for head, body in blocks:
        styles.append(0)
        lines.append(head)
        for part in textwrap.wrap(body, width):
            styles.append(1)
            lines.append(part)
        styles.append(2)
        lines.append("")
    return styles, lines


