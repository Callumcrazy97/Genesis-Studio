STAMP = "2026-10-28T00:00:00Z"


def guid(name):
    return hashlib.md5(("mushroom-meadow-product:" + name).encode("utf-8")).hexdigest()


def write_text(rel, text):
    path = os.path.join(ASSETS, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    text.encode("ascii")  # every generated script stays plain ASCII
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)


def write_meta(rel, kind, display):
    path = os.path.join(ASSETS, rel + ".meta")
    existing = None
    if os.path.exists(path):
        try:
            with open(path, encoding="utf-8") as handle:
                existing = json.load(handle).get("guid")
        except (OSError, ValueError):
            existing = None
    write_text(rel + ".meta", json.dumps({"guid": existing or guid(rel), "kind": kind, "displayName": display,
                                          "createdUtc": STAMP, "modifiedUtc": STAMP}, indent=2) + "\n")


def pgsl_list(items):
    return "[" + ", ".join(json.dumps(i) if isinstance(i, str) else repr(i) for i in items) + "]"


