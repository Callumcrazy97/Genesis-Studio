"""Mushroom Meadow PRODUCT generator: the player-facing features of a finished game.

Re-runnable and deterministic. Run from anywhere (after frontend_gen.py, before check_scripts.py):
    python BuildTools/TemplateContent/MushroomMeadow/product_gen.py
Writes into Source/Genesis.Application.Core/Projects/Templates/Assets/TwoDShowcase/Assets:

  Scripts/Difficulty Kit.pgsl      library: Story / Normal / Challenge (hearts, lives, timer, foe pace, grace, berries)
  Scripts/Achievements Kit.pgsl    library: 18 achievements, counters, the toast, per-level best times
  Scripts/Journal Kit.pgsl         library: the How to Play and Collection (stats, wildlife, achievements) pages
and, beside the template's project file, the game's icon (BuildTools/.../Mushroom Meadow.ico, also copied next
to the template's project file) made from the Pip portrait. The hooks that feed these kits live in the other
generators (hero_gen.py Explorer, gore_gen.py, hub_gen.py, frontend_gen.py, options_kit_gen.py).
"""
