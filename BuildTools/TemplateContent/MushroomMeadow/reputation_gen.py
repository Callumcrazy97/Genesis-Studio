def smoothstep(lo, hi, x):
    import numpy as np
    t = np.clip((x - lo) / (hi - lo), 0.0, 1.0)
    return t * t * (3.0 - 2.0 * t)


def lerp(a, b, t):
    return a + (b - a) * t


def tainted_portrait(src, amount):
    """The Pixel Flash taint (fx_gen.py) applied to a portrait: cap reds sink toward maroon, bruised violet
    and near black, the cream spots turn sickly pale green, the rest loses colour."""
    import numpy as np
    from PIL import Image
    from scipy import ndimage

    arr = np.asarray(src.convert("RGBA"), dtype=np.float64) / 255.0
    rgb = arr[:, :, :3].copy()
    alpha = arr[:, :, 3]
    r, g, b = rgb[:, :, 0], rgb[:, :, 1], rgb[:, :, 2]
    luma = rgb @ np.array([0.299, 0.587, 0.114])
    redness = smoothstep(0.38, 0.5, 1.0 - np.maximum(g, b) / np.maximum(r, 0.001)) * (alpha > 0.5)
    # The cap is the red region with its spots (holes) filled in.
    cap = ndimage.binary_fill_holes(ndimage.binary_closing(redness > 0.5, iterations=2))
    pale = smoothstep(0.70, 0.73, b / np.maximum(r, 0.001)) * smoothstep(0.78, 0.86, luma) * cap
    tone = np.clip((luma - 0.1) / 0.5, 0.0, 1.0)[:, :, None]

    def ramp(dark, light):
        return np.array(dark) * (1 - tone) + np.array(light) * tone

    maroon = ramp((0.17, 0.03, 0.07), (0.58, 0.12, 0.16))
    violet = ramp((0.13, 0.05, 0.21), (0.47, 0.22, 0.58))
    ember = ramp((0.025, 0.015, 0.045), (0.15, 0.10, 0.19))
    cap_tint = lerp(maroon, violet, np.clip((amount - 0.4) / 0.35, 0, 1))
    cap_tint = lerp(cap_tint, ember, np.clip((amount - 0.75) / 0.25, 0, 1))
    aged = lerp(rgb, luma[:, :, None] * np.array([0.96, 1.0, 0.92]), 0.3 * amount)
    aged = lerp(aged, cap_tint, (min(1.0, amount * 2.5) * redness)[:, :, None])
    sick = np.array([0.6, 0.96, 0.5]) * 0.95
    spot = (min(1.0, amount * 2.0) * pale)[:, :, None]
    aged = lerp(aged, sick, spot)
    aged = aged + np.array([0.1, 0.32, 0.08]) * spot * 0.35
    # The world around him dims a little too (everything but the cap).
    aged = aged * (1.0 - 0.18 * amount * (1.0 - cap[:, :, None]))
    out = np.concatenate([np.clip(aged, 0, 1), alpha[:, :, None]], axis=2)
    img = Image.fromarray((out * 255.0 + 0.5).astype(np.uint8), "RGBA").copy()
    px = img.load()
    # A few drifting spores near the cap at the later stages (fixed positions: deterministic).
    ys, xs = np.nonzero(cap)
    if len(xs) and amount >= 0.55:
        top, left, right = int(ys.min()), int(xs.min()), int(xs.max())
        specks = [(left + 3, top - 2), (right - 4, top - 1), (left + 12, top - 3)]
        if amount >= 0.85:
            specks += [(right + 1, top + 7), (left - 1, top + 9), (left + 24, top - 4)]
        for (sx, sy) in specks:
            if 0 <= sx < img.width and 0 <= sy < img.height and px[sx, sy][3] > 0:
                px[sx, sy] = (178, 250, 140, 255)
    return img


def build_portraits():
    sys.path.insert(0, HERE)
    from PIL import Image
    import world_art
    source = os.path.join(ASSETS, "Sprites", "Portrait Pip.image.json")
    with open(source, encoding="utf-8") as handle:
        doc = json.load(handle)
    frame = doc["frames"][0]["source"]
    base = Image.open(os.path.join(ASSETS, "Sprites", frame))
    for number, amount in ((1, 0.3), (2, 0.6), (3, 0.92)):
        name = "Portrait Pip Spore %d" % number
        img = tainted_portrait(base, amount)
        world_art.write_image(name, img, "sprite", (0, 0), template_name="Portrait Pip", tag_name="Still")


def main():
    build_kit()
    build_particles()
    build_portraits()
    print("Reputation content written to", ASSETS)


if __name__ == "__main__":
    main()
