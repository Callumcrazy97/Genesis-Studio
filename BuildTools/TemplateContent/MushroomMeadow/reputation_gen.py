"""Mushroom Meadow REPUTATION content generator: the Reputation Kit, Pip's spore leak and tainted portraits.

Re-runnable and deterministic. Run from anywhere (after creature_art.py, which writes Portrait Pip):
    python BuildTools/TemplateContent/MushroomMeadow/reputation_gen.py
Writes into Source/Genesis.Application.Core/Projects/Templates/Assets/TwoDShowcase/Assets:

  Scripts   Reputation Kit (library: RepKill, RepBrutality, RepStage, RepLabel, RepPriceMul, RepTaintAmount,
            RepDecay and a few helpers; see the header of the script)
  Particles Pip Spore Leak (the faint pale-green spores a tainted Pip leaks from his cap, stage 2 and up)
  Images    Portrait Pip Spore 1, 2, 3 (hue-shifted, darkened copies of Portrait Pip; needs Pillow, NumPy, SciPy)

Hidden lore (never explained in the game, only hinted): Pip's head is a mushroom, and a fungal infection of
his brain answers to how brutally he plays. The kit only keeps the numbers; the visuals live in the Pixel
Flash shader (fx_gen.py: Taint / TaintPulse), the dialogue (hub_gen.py) and the credits (frontend_gen.py).
"""
import hashlib
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
ASSETS = os.path.join(ROOT, "Source", "Genesis.Application.Core", "Projects", "Templates",
                      "Assets", "TwoDShowcase", "Assets")
STAMP = "2026-10-15T00:00:00Z"


def guid(name):
    return hashlib.md5(("mushroom-meadow-reputation:" + name).encode("utf-8")).hexdigest()


def write_text(rel, text):
    path = os.path.join(ASSETS, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    text.encode("ascii")  # keep every generated file plain ASCII
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)


def write_json(rel, data):
    write_text(rel, json.dumps(data, indent=2) + "\n")


def write_meta(rel, kind, display):
    path = os.path.join(ASSETS, rel + ".meta")
    existing = None
    if os.path.exists(path):
        try:
            with open(path, encoding="utf-8") as handle:
                existing = json.load(handle).get("guid")
        except (OSError, ValueError):
            existing = None
    write_json(rel + ".meta", {"guid": existing or guid(rel), "kind": kind, "displayName": display,
                               "createdUtc": STAMP, "modifiedUtc": STAMP})


def colour(r, g, b, a=1.0):
    return {"r": r, "g": g, "b": b, "a": a}


# ====================================================================== the kit
REPUTATION_KIT = """// Reputation Kit: how the valley sees Pip (library functions only; every name starts with Rep).
// Generated by BuildTools/TemplateContent/MushroomMeadow/reputation_gen.py.
//
// Globals (saved with the game): brutality (float 0..100), taintStage (0..3, derived by RepStage),
// killsStomp, killsBlade, killsArrow, killsGib, killsSliced, fearedBy (the Fear Kit counts it).
// Runtime only: repGrace (seconds before kindness starts to heal again).
//
// Brutality: a stomp is kind (-1), blades +4, arrows +3, shield bashes +2, spores and Starlit +1,
// a sliced body +4 extra, an overkill / gib +6 extra, killing a fleeing enemy +6 extra, a boss 0.
// Stage: 0 below 25, 1 below 50, 2 below 75, 3 from 75 (leaving a stage needs 3 points less).
//
// Hidden lore: this kit only keeps numbers. What the stages mean is never said in the game.

// Creates the globals when a room was started on its own. Returns 1.
function RepEnsure() {
    if (!GlobalExists("brutality")) { GlobalSet("brutality", 0); }
    if (!GlobalExists("taintStage")) { GlobalSet("taintStage", 0); }
    if (!GlobalExists("repGrace")) { GlobalSet("repGrace", 0); }
    if (!GlobalExists("killsStomp")) { GlobalSet("killsStomp", 0); }
    if (!GlobalExists("killsBlade")) { GlobalSet("killsBlade", 0); }
    if (!GlobalExists("killsArrow")) { GlobalSet("killsArrow", 0); }
    if (!GlobalExists("killsGib")) { GlobalSet("killsGib", 0); }
    if (!GlobalExists("killsSliced")) { GlobalSet("killsSliced", 0); }
    if (!GlobalExists("fearedBy")) { GlobalSet("fearedBy", 0); }
    return 1;
}

// A fresh adventurer: everything back to zero (New Game). Returns 1.
function RepReset() {
    GlobalSet("brutality", 0); GlobalSet("taintStage", 0); GlobalSet("repGrace", 0);
    GlobalSet("killsStomp", 0); GlobalSet("killsBlade", 0); GlobalSet("killsArrow", 0);
    GlobalSet("killsGib", 0); GlobalSet("killsSliced", 0); GlobalSet("fearedBy", 0);
    return 1;
}

// Brutality 0..100.
function RepBrutality() {
    return Clamp(GlobalGet("brutality"), 0, 100);
}

// Adds to (or, negative, takes from) the brutality; returns the new value.
function RepAdd(amount) {
    var total = Clamp(GlobalGet("brutality") + amount, 0, 100);
    GlobalSet("brutality", total);
    RepStage();
    return total;
}

// The taint stage 0..3 with a hysteresis of 3 points (a stage is entered at 25 / 50 / 75 and left 3 below).
function RepStage() {
    var total = Clamp(GlobalGet("brutality"), 0, 100);
    var stage = Clamp(Floor(GlobalGet("taintStage")), 0, 3);
    while (stage < 3 && total >= 25 * (stage + 1)) { stage = stage + 1; }
    while (stage > 0 && total < 25 * stage - 3) { stage = stage - 1; }
    if (stage != GlobalGet("taintStage")) { GlobalSet("taintStage", stage); }
    return stage;
}

// 1 while Pip has played gently: stage 0, almost no brutality and a few stomps behind him.
function RepIsKind() {
    if (RepStage() == 0 && GlobalGet("brutality") < 8 && GlobalGet("killsStomp") >= 3) { return 1; }
    return 0;
}

// The word for the pause menu and the credits: BELOVED, RESPECTED, KNOWN, WARY, FEARED or DREADED.
function RepLabel() {
    var stage = RepStage();
    var total = RepBrutality();
    if (stage >= 3) { return "DREADED"; }
    if (stage == 2) { return "FEARED"; }
    if (stage == 1) {
        if (total >= 38) { return "WARY"; }
        return "KNOWN";
    }
    if (RepIsKind() == 1) { return "BELOVED"; }
    return "RESPECTED";
}

// The shop multiplier 0.75 .. 1.6 (a friendly discount for a gentle record, a surcharge for a brutal one).
function RepPriceMul() {
    var total = RepBrutality();
    var mul = 1;
    if (total < 10) { mul = Lerp(0.9, 1.0, total / 10); }
    else if (total < 25) { mul = Lerp(1.0, 1.08, (total - 10) / 15); }
    else if (total < 50) { mul = Lerp(1.08, 1.25, (total - 25) / 25); }
    else if (total < 75) { mul = Lerp(1.25, 1.5, (total - 50) / 25); }
    else { mul = Lerp(1.5, 1.6, (total - 75) / 25); }
    if (total < 10) {
        var stomps = Clamp(GlobalGet("killsStomp") / 12, 0, 1);
        mul = mul - 0.15 * stomps * (1 - total / 10);
    }
    return Clamp(mul, 0.75, 1.6);
}

// A base price in whole coins after the multiplier (never below 1).
function RepPrice(base) {
    return Max(1, Round(base * RepPriceMul()));
}

// The shop multiplier as a whole percent: -25 .. +60.
function RepPricePercent() {
    return Round((RepPriceMul() - 1) * 100);
}

// 0..1 for the Pixel Flash shader's Taint parameter (0 while brutality is 10 or less).
function RepTaintAmount() {
    var total = RepBrutality();
    if (total <= 10) { return 0; }
    if (total < 25) { return Lerp(0, 0.2, (total - 10) / 15); }
    if (total < 50) { return Lerp(0.2, 0.5, (total - 25) / 25); }
    if (total < 75) { return Lerp(0.5, 0.8, (total - 50) / 25); }
    return Lerp(0.8, 1, (total - 75) / 25);
}

// Kindness heals a little: 0.15 per second, only below 40 and only after a quiet spell (repGrace).
function RepDecay(dt) {
    var grace = GlobalGet("repGrace");
    if (grace > 0) {
        GlobalSet("repGrace", Max(0, grace - dt));
        return 0;
    }
    var total = GlobalGet("brutality");
    if (total > 0 && total < 40) { GlobalSet("brutality", Max(0, total - 0.15 * dt)); }
    return 0;
}

// An enemy died. hitKind: 1 stomp, 2 sword, 3 arrow, 4 thrown item, 5 spore shot, 6 starlit touch,
// 7 shield bash, 8 other. overkill / sliced: 1 when the Gore Kit gibbed / cut the body.
// weak: 1 for a small enemy (2 marks a boss, as does an `isBoss` variable of 1 on the calling enemy).
// The calling enemy's `feared` variable (Fear Kit) adds 6 for killing something that was running away.
// Returns the brutality change (0 for a boss).
function RepKill(hitKind, overkill, sliced, weak) {
    RepEnsure();
    var me = self.id;
    var boss = 0;
    if (weak >= 2) { boss = 1; }
    if (InstanceVariableExists(me, "isBoss")) {
        if (InstanceVariableGet(me, "isBoss") == 1) { boss = 1; }
    }
    if (boss == 1) { return 0; }
    var gain = 0;
    if (hitKind == 1) {
        gain = -1;
        GlobalSet("killsStomp", GlobalGet("killsStomp") + 1);
    } else if (hitKind == 2 || hitKind == 4) {
        gain = 4;
        GlobalSet("killsBlade", GlobalGet("killsBlade") + 1);
    } else if (hitKind == 3) {
        gain = 3;
        GlobalSet("killsArrow", GlobalGet("killsArrow") + 1);
    } else if (hitKind == 7) {
        gain = 2;
        GlobalSet("killsBlade", GlobalGet("killsBlade") + 1);
    } else if (hitKind == 5 || hitKind == 6) {
        gain = 1;
    }
    if (sliced != 0) {
        gain = gain + 4;
        GlobalSet("killsSliced", GlobalGet("killsSliced") + 1);
    }
    if (overkill != 0) {
        gain = gain + 6;
        GlobalSet("killsGib", GlobalGet("killsGib") + 1);
    }
    if (InstanceVariableExists(me, "feared")) {
        if (InstanceVariableGet(me, "feared") == 1) { gain = gain + 6; }
    }
    if (gain != 0) { RepAdd(gain); }
    if (gain > 0) { GlobalSet("repGrace", 10); }
    return gain;
}
"""


